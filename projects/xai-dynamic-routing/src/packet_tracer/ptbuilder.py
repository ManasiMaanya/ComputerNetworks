"""JavaScript for Packet Tracer's Script Engine (run via PTBuilder).

The generated scripts are self-contained - they call PT's IPC API
directly (``ipc.appWindow().getActiveWorkspace().getLogicalWorkspace()``,
``ipc.network().getDevice()``, ``Device.enterCommand()``, ...), the same
calls PTBuilder's own helpers make - so they only need *somewhere* to run
inside PT. The intended runner is PTBuilder's **Builder Code Editor**
(https://github.com/kimmknight/PTBuilder): paste the script, click Run.

Every step is wrapped in ``try``/``catch`` (an uncaught error opens a modal
dialog that can freeze PT's script window) and the script ends with one
summary message box listing what failed, if anything. Data is embedded as
JSON and the code is plain ES5 (``var``, ``for``), which PT's Script Engine
accepts.

The Builder Code Editor removes every newline before running the code
(PTBuilder interface.js: ``code.replace(/\\n/g, "")``), so the scripts must not
depend on line breaks: no ``//`` comments (they would swallow the rest of the
script), explicit semicolons everywhere. tests/js/pt_mock.js applies the same
transformation.
"""

from __future__ import annotations

import json

from .plan import (
    CABLE_TYPES,
    HOST_MODEL,
    HOST_PORT,
    HOST_TYPE,
    ROUTER_MODEL,
    ROUTER_TYPE,
    NetworkPlan,
)

_RUNTIME = r"""
var lw = ipc.appWindow().getActiveWorkspace().getLogicalWorkspace();
var net = ipc.network();
var errors = [];
var ok = 0;

function attempt(what, fn) {
    try {
        if (fn() === false) { errors.push(what + ": failed"); } else { ok++; }
    } catch (e) {
        errors.push(what + ": " + e);
    }
}

function addDevice(d) {
    if (net.getDevice(d.name)) {
        throw "a device named " + d.name + " already exists - run this in an empty workspace";
    }
    var autoName = lw.addDevice(d.type, d.model, d.x, d.y);
    if (!autoName) { return false; }
    var dev = net.getDevice(autoName);
    dev.setName(d.name);
    if (d.type <= 1 || d.type == 16) { dev.skipBoot(); }
    return true;
}

function addLink(l) {
    return lw.createLink(l.a, l.aPort, l.b, l.bPort, l.cable) !== false;
}

function configureIos(name, lines) {
    var dev = net.getDevice(name);
    if (!dev) { throw "no device named " + name; }
    var type = dev.getType();
    if (type <= 1 || type == 16) { dev.skipBoot(); }
    dev.enterCommand("!", "global");
    for (var i = 0; i < lines.length; i++) {
        dev.enterCommand(lines[i], "");
    }
    dev.enterCommand("end", "");
    dev.enterCommand("write memory", "enable");
}

function configureHost(h) {
    var dev = net.getDevice(h.name);
    if (!dev) { throw "no device named " + h.name; }
    var port = dev.getPort(h.port);
    port.setIpSubnetMask(h.ip, h.mask);
    if (typeof dev.setDefaultGateway === "function") { dev.setDefaultGateway(h.gateway); }
    else { port.setDefaultGateway(h.gateway); }
}

function report(title) {
    var text = title + ": " + ok + " step(s) OK, " + errors.length + " failed.";
    var detail = errors.join("\n");
    try {
        ipc.appWindow().showMessageBox(title, text, detail, errors.length ? 3 : 1, 0x00000400, 0x00000400, 0x00000400);
    } catch (e) {
        try { console.log(text + "\n" + detail); } catch (e2) {}
    }
}
"""


def _header(title: str, lines: list[str]) -> str:
    # Block comment, never "//": PTBuilder strips every newline before running the editor
    # contents, so a line comment would swallow the whole script.
    body = [title, "Generated by xai-dynamic-routing: scripts/packet_tracer.py", *lines]
    return "/*\n" + "\n".join(f" * {line.replace('*/', '* /')}" for line in body) + "\n */\n"


def _js(value) -> str:
    return json.dumps(value, indent=1)


def build_script(plan: NetworkPlan, protocol: str, configs: dict[str, list[str]]) -> str:
    """Script that creates every device and cable and applies ``configs``."""
    devices = [
        {"name": r, "type": ROUTER_TYPE, "model": ROUTER_MODEL, "x": plan.positions[r][0], "y": plan.positions[r][1]}
        for r in plan.routers
    ] + [
        {"name": h.name, "type": HOST_TYPE, "model": HOST_MODEL, "x": plan.positions[h.name][0], "y": plan.positions[h.name][1]}
        for h in plan.hosts.values()
    ]
    links = [
        {"a": c.a_device, "aPort": c.a_port, "b": c.b_device, "bPort": c.b_port, "cable": CABLE_TYPES[c.kind]}
        for c in plan.cables
    ]
    hosts = [
        {"name": h.name, "port": HOST_PORT, "ip": h.ip, "mask": h.mask, "gateway": h.gateway}
        for h in plan.hosts.values()
    ]
    stripped = {r: [line.strip() for line in lines] for r, lines in configs.items()}
    title = f"XAI routing - build ({protocol.upper()})"
    body = f"""
(function () {{
{_RUNTIME}
var DEVICES = {_js(devices)};
var LINKS = {_js(links)};
var CONFIGS = {_js(stripped)};
var HOSTS = {_js(hosts)};

for (var i = 0; i < DEVICES.length; i++) {{
    (function (d) {{ attempt("add " + d.name, function () {{ return addDevice(d); }}); }})(DEVICES[i]);
}}
for (var j = 0; j < LINKS.length; j++) {{
    (function (l) {{ attempt("cable " + l.a + " " + l.aPort + " - " + l.b + " " + l.bPort, function () {{ return addLink(l); }}); }})(LINKS[j]);
}}
for (var name in CONFIGS) {{
    (function (n) {{ attempt("configure " + n, function () {{ configureIos(n, CONFIGS[n]); }}); }})(name);
}}
for (var k = 0; k < HOSTS.length; k++) {{
    (function (h) {{ attempt("address " + h.name, function () {{ configureHost(h); }}); }})(HOSTS[k]);
}}
report({json.dumps(title)});
}})();
"""
    header = _header(title, [
        "Run in an EMPTY Packet Tracer workspace: Extensions > Builder Code Editor, paste, Run.",
        f"Builds {len(plan.routers)} {ROUTER_MODEL} L3 switches (as routers) + {len(plan.hosts)} PCs, "
        f"{len(plan.cables)} cables, {protocol.upper()} routing.",
    ])
    return header + body


def routes_script(title: str, commands: dict[str, list[str]], note: str) -> str:
    """Script that enters extra config lines (e.g. AI static routes) on existing devices."""
    body = f"""
(function () {{
{_RUNTIME}
var CONFIGS = {_js(commands)};
for (var name in CONFIGS) {{
    (function (n) {{ attempt("configure " + n, function () {{ configureIos(n, CONFIGS[n]); }}); }})(name);
}}
report({json.dumps(title)});
}})();
"""
    return _header(title, [note, "Run in the workspace built by a build_*.js script: Extensions > Builder Code Editor, paste, Run."]) + body
