"""Label sensitivity: does the model merely re-learn whatever cost formula it is given?

The default labels are the configured scoring rule's realized cost over the next horizon. If
the model is "just the formula", changing the cost weights should change both the rule's
preferred path and the model's preferred path in the same direction. This module makes that
comparison explicit by retraining under alternative weight vectors:

  * `delay_heavy`, `risk_heavy`, `loss_congestion_heavy`, `hop_heavy`: one policy dimension
    is multiplied (others unchanged), then weights are rescaled to the baseline total so the
    hard-constraint penalty keeps the same relative strength.
  * `uniform`: every term has the same weight.
  * `random_N`: seeded Dirichlet draws over the ten terms.

Two path-choice rates are reported per scenario on the same held-out queries:
  * `rule_change_rate`: the rule's argmin path changes relative to the baseline weights;
  * `model_change_rate`: the retrained model's pick changes relative to the baseline model.
If they move together, the model tracks the declared policy. That is the honest reading: it
does not discover a weight-free truth. `transfer_*` scores the baseline model against the new
labels without retraining, showing that adaptation needs the new definition, not just a new
view of the old model.
"""

from __future__ import annotations

