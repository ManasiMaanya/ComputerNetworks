LIMITATIONS = [
    "Each scenario is retrained on labels generated by that scenario's weights; the model is not asked to infer weights it never saw.",
    "Weights, references and the hard-constraint penalty are a declared policy, not an objective ground truth.",
    "Change rates depend on the candidate set (k and max_hops); a weight change that is invisible within five candidates is not measured.",
    "Random Dirichlet draws are exploratory and seeded; they are not a full sensitivity surface.",
]

SCENARIO_MULTIPLIERS = {
    "delay_heavy": {"delay": 4.0},
    "risk_heavy": {"security_risk": 4.0},
    "loss_congestion_heavy": {"loss": 3.0, "congestion": 3.0},
    "hop_heavy": {"hops": 10.0},
}


def _baseline_weights(scoring: dict) -> dict[str, float]:
    weights = {term: max(0.0, float(scoring["weights"].get(term, 0.0))) for term in SCORE_TERMS}
    if sum(weights.values()) <= 0:
        raise ConfigError("scoring.weights: at least one weight must be > 0")
    return weights


def _rescale(weights: dict[str, float], total: float) -> dict[str, float]:
    clean = {term: max(0.0, float(weights.get(term, 0.0))) for term in SCORE_TERMS}
    current = sum(clean.values())
    if current <= 0:
        raise ConfigError("weight scenario has no positive weight")
    return {term: value / current * total for term, value in clean.items()}


def weight_scenarios(base_scoring: dict, *, random_draws: int = 2, seed: int = 7) -> dict[str, dict]:
    """Full scoring dicts for the baseline plus named and random weight scenarios."""
    base = _baseline_weights(base_scoring)
    total = sum(base.values())
    scenarios = {"baseline": copy.deepcopy(base_scoring)}

    def add(name: str, weights: dict[str, float]) -> None:
        scoring = copy.deepcopy(base_scoring)
        scoring["weights"] = _rescale(weights, total)
        scenarios[name] = scoring

    for name, multipliers in SCENARIO_MULTIPLIERS.items():
        add(name, {term: base[term] * multipliers.get(term, 1.0) for term in SCORE_TERMS})
    add("uniform", {term: 1.0 for term in SCORE_TERMS})
    rng = np.random.default_rng(seed)
    for i in range(max(0, int(random_draws))):
        draw = rng.dirichlet(np.ones(len(SCORE_TERMS)))
        add(f"random_{i + 1}", dict(zip(SCORE_TERMS, draw)))
    return scenarios


def _first_min(values: np.ndarray) -> int:
    return int(np.lexsort((np.arange(len(values)), values))[0])


def rule_pick_change_rate(scenario_table: pd.DataFrame, test_mask: np.ndarray,
                          base_scoring: dict, scenario_scoring: dict) -> dict:
    """How often the rule's preferred candidate changes between two weight vectors."""
    test = scenario_table[test_mask]
    if test.empty:
        return {"queries": 0, "changed": 0, "change_rate": None, "mean_cost_spearman": None}
    base_cost = path_cost(test[list(FEATURE_COLUMNS)], base_scoring).to_numpy()
    scenario_cost = path_cost(test[list(FEATURE_COLUMNS)], scenario_scoring).to_numpy()
    frame = test.assign(_base_cost=base_cost, _scenario_cost=scenario_cost)
    changed, correlations = 0, []
    queries = 0
    for _, group in frame.groupby("query", sort=False):
        group = group.sort_values("path_id")
        queries += 1
        base_idx = _first_min(group["_base_cost"].to_numpy())
        scenario_idx = _first_min(group["_scenario_cost"].to_numpy())
        changed += int(group.iloc[base_idx]["path_id"] != group.iloc[scenario_idx]["path_id"])
        if len(group) >= 2 and group["_base_cost"].nunique() > 1 and group["_scenario_cost"].nunique() > 1:
            correlations.append(float(group["_base_cost"].corr(group["_scenario_cost"], method="spearman")))
    return {
        "queries": queries,
        "changed": changed,
        "change_rate": (changed / queries) if queries else None,
        "mean_cost_spearman": float(np.mean(correlations)) if correlations else None,
    }


def model_pick_change_rate(base_model, scenario_model, scenario_table: pd.DataFrame,
                           test_mask: np.ndarray) -> dict:
    """How often the retrained model's pick changes relative to the baseline model."""
    test = scenario_table[test_mask]
    if test.empty:
        return {"queries": 0, "changed": 0, "change_rate": None,
                "mean_abs_prediction_delta": None}
    base_pred = base_model.predict(test[list(MODEL_COLUMNS)])
    scenario_pred = scenario_model.predict(test[list(MODEL_COLUMNS)])
    frame = test.assign(_base_pred=base_pred, _scenario_pred=scenario_pred)
    changed = queries = 0
    for _, group in frame.groupby("query", sort=False):
        group = group.sort_values("path_id")
        queries += 1
        hops = group["hops"].to_numpy()
        base_idx = int(selection_order(group["_base_pred"].to_numpy(), hops)[0])
        scenario_idx = int(selection_order(group["_scenario_pred"].to_numpy(), hops)[0])
        changed += int(group.iloc[base_idx]["path_id"] != group.iloc[scenario_idx]["path_id"])
    return {
        "queries": queries,
        "changed": changed,
        "change_rate": (changed / queries) if queries else None,
        "mean_abs_prediction_delta": float(np.mean(np.abs(scenario_pred - base_pred))),
    }


def _transfer_metrics(base_model, scenario_table: pd.DataFrame, test_mask: np.ndarray) -> dict:
    test = scenario_table[test_mask]
    if test.empty:
        return {"top1": None, "mean_regret": None, "mae": None, "queries": 0}
    pred = base_model.predict(test[list(MODEL_COLUMNS)])
    selection = evaluate_selection(test, pred)
    return {
        "top1": selection["methods"]["model"]["top1"],
        "mean_regret": selection["methods"]["model"]["mean_regret"],
        "mae": float(np.mean(np.abs(pred - test["target"].to_numpy()))),
        "queries": int(selection["queries"]),
    }


def study_label_sensitivity(graph, cfg: dict, *, scenarios: dict[str, dict] | None = None,
                            include_blackbox: bool = False, cv: bool = False,
                            log=print) -> dict:
    """Retrain under each weight scenario and compare rule vs model path changes."""
    scenarios = scenarios or weight_scenarios(
        cfg["scoring"],
        random_draws=int(cfg.get("evaluation", {}).get("label_sensitivity", {})
                         .get("random_weight_draws", 2)),
        seed=int(cfg.get("evaluation", {}).get("label_sensitivity", {}).get("seed", 7)))
    if "baseline" not in scenarios:
        scenarios = {"baseline": copy.deepcopy(cfg["scoring"]), **scenarios}
    baseline_name = "baseline"
    tcfg = cfg["training"]

    fitted: dict[str, dict] = {}
    for name, scoring in scenarios.items():
        scfg = copy.deepcopy(cfg)
        scfg["scoring"] = scoring
        table = build_training_table(graph, scfg)
        train_mask, test_mask = split_groups(table, tcfg["test_size"], tcfg["seed"])
        model, report, _ = train_and_evaluate(table, train_mask, test_mask, scfg,
                                              blackbox=include_blackbox, cv=cv)
        fitted[name] = {"model": model, "report": report, "table": table,
                        "train_mask": train_mask, "test_mask": test_mask, "scoring": scoring}
        top1 = report["test_selection"]["model_top1_accuracy"]
        log(f"{name:<22} rows={len(table):>6}  model top-1={top1:.3f}  "
            f"MAE={report['test_regression']['mae']:.4f}  R2={report['test_regression']['r2']:.4f}")

    baseline = fitted[baseline_name]
    results: dict[str, dict] = {}
    for name, item in fitted.items():
        report = item["report"]
        if name == baseline_name:
            held_out = int(item["table"][item["test_mask"]]["query"].nunique())
            rule = {"queries": held_out, "changed": 0, "change_rate": 0.0,
                    "mean_cost_spearman": 1.0}
            model_change = {"queries": held_out, "changed": 0,
                            "change_rate": 0.0, "mean_abs_prediction_delta": 0.0}
            transfer = {
                "top1": report["test_selection"]["model_top1_accuracy"],
                "mean_regret": report["test_selection"]["model_mean_regret"],
                "mae": report["test_regression"]["mae"],
                "queries": report["test_selection"]["queries"],
            }
        else:
            rule = rule_pick_change_rate(item["table"], item["test_mask"],
                                         baseline["scoring"], item["scoring"])
            model_change = model_pick_change_rate(baseline["model"], item["model"],
                                                  item["table"], item["test_mask"])
            transfer = _transfer_metrics(baseline["model"], item["table"], item["test_mask"])
        results[name] = {
            "weights": {term: float(item["scoring"]["weights"].get(term, 0.0))
                        for term in SCORE_TERMS},
            "rows": int(len(item["table"])),
            "queries": int(report["test_selection"]["queries"]),
            "model_top1": report["test_selection"]["model_top1_accuracy"],
            "model_mean_regret": report["test_selection"]["model_mean_regret"],
            "snapshot_rule_top1": report["test_selection"]["methods"]["snapshot_rule"]["top1"],
            "mae": report["test_regression"]["mae"],
            "r2": report["test_regression"]["r2"],
            "top_features": [{"feature": feature, "importance": float(value)}
                             for feature, value in list(report["feature_importance_impurity"].items())[:5]],
            "rule_vs_baseline": rule,
            "model_vs_baseline": model_change,
            "transfer_from_baseline": transfer,
        }

    changed = [name for name in results if name != baseline_name]
    rule_rates = [results[name]["rule_vs_baseline"]["change_rate"] for name in changed
                  if results[name]["rule_vs_baseline"]["change_rate"] is not None]
    model_rates = [results[name]["model_vs_baseline"]["change_rate"] for name in changed
                   if results[name]["model_vs_baseline"]["change_rate"] is not None]
    retrained = [results[name]["model_top1"] for name in changed
                 if results[name]["model_top1"] is not None]
    transferred = [results[name]["transfer_from_baseline"]["top1"] for name in changed
                   if results[name]["transfer_from_baseline"]["top1"] is not None]
    correlation = None
    if len(rule_rates) >= 3 and len(rule_rates) == len(model_rates):
        if np.ptp(rule_rates) > 0 and np.ptp(model_rates) > 0:
            correlation = float(np.corrcoef(rule_rates, model_rates)[0, 1])

    summary = {
        "scenarios": len(results),
        "held_out_queries": int(results[baseline_name]["queries"]),
        "mean_rule_change_rate": float(np.mean(rule_rates)) if rule_rates else None,
        "mean_model_change_rate": float(np.mean(model_rates)) if model_rates else None,
        "tracking_gap": (float(np.mean(model_rates)) - float(np.mean(rule_rates)))
                        if rule_rates and model_rates else None,
        "rule_model_change_correlation": correlation,
        "mean_retrained_top1": float(np.mean(retrained)) if retrained else None,
        "mean_transfer_top1": float(np.mean(transferred)) if transferred else None,
        "transfer_gap": (float(np.mean(retrained)) - float(np.mean(transferred)))
                        if retrained and transferred else None,
        "interpretation": (
            "A high retrained top-1 under each weight vector and a model change rate close to the "
            "rule change rate mean the model tracks the declared policy. The lower transfer top-1 "
            "shows that the old model does not automatically adopt a new cost definition; retraining "
            "on the new labels is what changes its recommendations."
        ),
    }
    return {
        "method": "label sensitivity over alternative scoring weights (retrain per scenario)",
        "labels": tcfg["labels"],
        "seed": tcfg["seed"],
        "baseline": baseline_name,
        "scenarios": results,
        "summary": summary,
        "limitations": LIMITATIONS,
    }


def label_sensitivity_figure(report: dict, path: Path) -> None:
    scenarios = report.get("scenarios", {})
    names = [name for name in scenarios if name != report.get("baseline")]
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.3))
    if names:
        x = np.arange(len(names))
        width = 0.38
        rule = [scenarios[name]["rule_vs_baseline"]["change_rate"] or 0.0 for name in names]
        model = [scenarios[name]["model_vs_baseline"]["change_rate"] or 0.0 for name in names]
        ax1.bar(x - width / 2, rule, width, label="rule pick changed", color="#7f8c8d")
        ax1.bar(x + width / 2, model, width, label="model pick changed", color="#2471a3")
        ax1.set_xticks(x, names, rotation=25, ha="right")
        ax1.set_ylim(0, 1)
        ax1.set_ylabel("fraction of held-out queries")
        ax1.set_title("Path changes vs baseline weights")
        ax1.legend(fontsize=8)

        retrained = [scenarios[name]["model_top1"] or 0.0 for name in names]
        transfer = [scenarios[name]["transfer_from_baseline"]["top1"] or 0.0 for name in names]
        ax2.bar(x - width / 2, retrained, width, label="retrained on scenario", color="#27ae60")
        ax2.bar(x + width / 2, transfer, width, label="baseline model transferred", color="#c0392b")
        ax2.set_xticks(x, names, rotation=25, ha="right")
        ax2.set_ylim(0, 1)
        ax2.set_ylabel("top-1 accuracy (true label)")
        ax2.set_title("Adaptation requires the new labels")
        ax2.legend(fontsize=8)
    else:
        for ax in (ax1, ax2):
            ax.text(0.5, 0.5, "no alternative scenarios", ha="center", va="center")
            ax.set_axis_off()
    fig.suptitle("Label sensitivity: model vs scoring-rule response to cost weights")
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def label_sensitivity_markdown(report: dict) -> str:
    summary = report.get("summary", {})
    lines = ["# Label sensitivity", "",
             f"Labels: `{report['labels']}`, seed {report['seed']}, baseline `{report['baseline']}`.",
             "", "## Summary", "", "| Metric | Value |", "|---|---|"]
    for key, value in summary.items():
        lines.append(f"| {key} | {value:.4f} |" if isinstance(value, float) else f"| {key} | {value} |")
    lines += ["", "## Scenarios", "",
              "| Scenario | Rule change | Model change | Retrained top-1 | Transfer top-1 | MAE | R2 | Top feature |",
              "|---|---|---|---|---|---|---|---|"]
    for name, row in report.get("scenarios", {}).items():
        rule = row["rule_vs_baseline"]["change_rate"]
        model = row["model_vs_baseline"]["change_rate"]
        top = row["top_features"][0]["feature"] if row["top_features"] else "n/a"
        fmt = lambda value: "n/a" if value is None else (
            f"{value:.4f}" if isinstance(value, float) else str(value))  # noqa: E731
        lines.append(f"| {name} | {fmt(rule)} | {fmt(model)} | {fmt(row['model_top1'])} | "
                     f"{fmt(row['transfer_from_baseline']['top1'])} | {fmt(row['mae'])} | "
                     f"{fmt(row['r2'])} | {top} |")
    lines += ["", "## Limitations", ""] + [f"- {item}" for item in report.get("limitations", [])]
    return "\n".join(lines) + "\n"
